let activeLanguage = "en";
const originalText = new WeakMap();
const originalAttributes = new WeakMap();

export function getLanguage() {
  return activeLanguage;
}

export function getLocale() {
  return LANGUAGES[activeLanguage].locale;
}

export function t(source, values = {}) {
  let output = translations[activeLanguage]?.[source] || source;
  for (const [key, value] of Object.entries(values)) {
    output = output.replaceAll(`{${key}}`, String(value));
  }
  return output;
}

export function formatCurrency(value) {
  return new Intl.NumberFormat(getLocale(), {
    style: "currency",
    currency: "EUR",
  }).format(Number(value) || 0);
}

export function formatDate(value, options = {}) {
  const date = value instanceof Date
    ? value
    : new Date(/^\d{4}-\d{2}-\d{2}$/.test(String(value)) ? `${value}T12:00:00` : value);
  return date.toLocaleDateString(getLocale(), options);
}

function translateStaticContent() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const normalized = source.replace(/\s+/g, " ").trim();
    const translated = t(normalized);
    if (translated === normalized) continue;
    const leading = source.match(/^\s*/)?.[0] || "";
    const trailing = source.match(/\s*$/)?.[0] || "";
    node.nodeValue = `${leading}${translated}${trailing}`;
  }

  for (const element of document.querySelectorAll("[placeholder], [title], [aria-label]")) {
    let attributes = originalAttributes.get(element);
    if (!attributes) {
      attributes = {};
      for (const name of ["placeholder", "title", "aria-label"]) {
        if (element.hasAttribute(name)) attributes[name] = element.getAttribute(name);
      }
      originalAttributes.set(element, attributes);
    }
    for (const [name, value] of Object.entries(attributes)) {
      element.setAttribute(name, t(value));
    }
  }

  document.title = t("Partly — PC build & price tracker");
  document.documentElement.lang = LANGUAGES[activeLanguage].html;
}

export function initializeI18n() {
  const select = document.getElementById("languageSelect");
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (saved && LANGUAGES[saved]) activeLanguage = saved;
  } catch {}
  if (select) {
    select.value = activeLanguage;
    select.addEventListener("change", () => {
      if (!LANGUAGES[select.value]) return;
      activeLanguage = select.value;
      try { localStorage.setItem(LANGUAGE_KEY, activeLanguage); } catch {}
      translateStaticContent();
      window.dispatchEvent(new CustomEvent("partly:languagechange", {
        detail: { language: activeLanguage },
      }));
    });
  }
  translateStaticContent();
}
